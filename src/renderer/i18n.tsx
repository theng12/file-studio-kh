const resources: Record<Language, Record<Key, string>> = { en, km };
const I18nContext = createContext<{ language: Language; t: (key: Key) => string }>({
  language: 'en',
  t: (key) => en[key],
});

export function translate(language: Language | undefined, key: Key): string {
  const nextLanguage = language === 'km' ? 'km' : 'en';
  return resources[nextLanguage][key] ?? en[key];
}

export function I18nProvider({ language, children }: { language: Language; children: React.ReactNode }) {
  return (
    <I18nContext.Provider value={{ language, t: (key) => translate(language, key) }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  return useContext(I18nContext);
}
